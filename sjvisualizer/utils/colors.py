def from_rgb(rgb: Iterable[int]) -> str:
    """Convert an (R,G,B) iterable to a Tk color string (#rrggbb).

    Negative channels are clamped to 0 to preserve legacy behavior.
    """

    r, g, b = [max(0, int(c)) for c in rgb]
    return f"#{r:02x}{g:02x}{b:02x}"


def hex_to_rgb(h: str) -> Tuple[int, int, int]:
    h = h.strip()
    return tuple(int(h.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore
